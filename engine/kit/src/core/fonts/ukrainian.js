// Ukrainian. The 33 letters, for each glyph set. Twelve capitals (А В Е І К М Н О Р С Т Х) and
// eight lowercase letters (а е і о р с у х) are the Latin shapes and are shared, not redrawn; З is
// the figure 3. Everything else is drawn here, on the same grids and by the same rules.
// Ї and Й carry their marks above the cap line, in the rows every set keeps free for them.
// Ц, Щ and Д stand on the baseline in the small sets (their tails are inside the cap height) and
// descend two cells in Vox Block, where a tail inside the letter would cost the bowl its height.
// Ф and Ю are wider than their neighbours so that their counters stay more than half open once
// the top and side of the cubes are drawn into them (tools/type-fill.mjs is the gate).

// Letters that are the same shape as a Latin glyph already in the set.
