import { connectSound } from '../switch-sound.js';
import { restore } from '../../src/index.js';
import { show } from './parts.js';

connectSound(document.querySelector('#catalog-sound'));

const groups = [...document.querySelectorAll('.group')];
const search = document.querySelector('#query');
const sheetToggle = document.querySelector('#sheets');
const level = document.querySelector('#level');
level.addEventListener('input', () => {
  document.querySelector('#level-out').value = level.value + '%';
});

function filter() {
  const query = search.value.trim().toLowerCase();
  let count = 0;
  for (const group of groups) {
    const title = group.querySelector('h2').textContent.toLowerCase();
    let matches = 0;
    for (const row of group.querySelectorAll('li')) {
      const name = row.firstElementChild.textContent.toLowerCase();
      row.hidden = !title.includes(query) && !name.includes(query);
      if (!row.hidden) matches++;
    }
    group.hidden = !matches;
    count += matches;
  }
  document.querySelector('#count').value = count === 0 ? 'No matching parts' : count === 1 ? '1 part' : count + ' parts';
}

// Generated by tools/part.mjs on demand. A fresh checkout has the full catalog without them.
const sheetNote = document.querySelector('#sheet-note');
sheetToggle.addEventListener('change', () => {
  sheetNote.hidden = !sheetToggle.checked;
  document.body.classList.toggle('with-sheets', sheetToggle.checked);
  if (!sheetToggle.checked) return;
  if (sheetNote.textContent) return;
  const rows = [...document.querySelectorAll('.group li')];
  let pending = rows.length;
  let found = 0;
  function done() {
    if (--pending) return;
    sheetNote.textContent = found ? found + ' test sheets available.' : 'No test sheets have been generated in this checkout.';
  }
  sheetNote.textContent = 'Looking for generated test sheets…';
  for (const row of rows) {
    const part = row.firstElementChild.getAttribute('href').replace(/\.html$/, '');
    const base = '../../shots/parts/' + part + '/';
    const image = new Image();
    image.alt = row.firstElementChild.textContent + ' test sheet';
    image.onload = () => {
      const link = document.createElement('a');
      link.href = base + 'sheet.png';
      link.className = 'sheet-link';
      link.append(image);
      row.append(link);
      found++;
      done();
    };
    image.onerror = done;
    image.src = base + 'thumb.jpg';
  }
});
search.addEventListener('input', filter);
filter();
document.querySelector('.toolbar').hidden = false;
await restore();
await show();
