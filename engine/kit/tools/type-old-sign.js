export const GLYPH_HEIGHT = 7;

/** Lay a string out as cells. Returns { cells: [[x, y], ...], width } in glyph units. */
export function layout(text, gap = 1) {
  const cells = [];
  let x = 0;
  for (const ch of String(text).toUpperCase()) {
    const g = G[ch] ?? G['?'];
    const w = g[0].length;
    for (let r = 0; r < 7; r++) for (let c = 0; c < w; c++) if (g[r][c] === '#') cells.push([x + c, r]);
    x += w + gap;
  }
  return { cells, width: Math.max(0, x - gap) };
}

export function measure(text, gap = 1) {
  return layout(text, gap).width;
}
